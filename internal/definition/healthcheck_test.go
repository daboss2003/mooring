// An empty array has always meant "no healthcheck": it still parses, the canonical omits it,
// and nothing is generated.
func TestHealthcheckEmptyArrayIsNone(t *testing.T) {
	d, err := Parse(healthDoc("[]"))
	if err != nil {
		t.Fatalf("healthcheck: [] must still parse: %v", err)
	}
	canon, _ := Canonical(d)
	if strings.Contains(string(canon), "healthcheck") {
		t.Errorf("an empty healthcheck must be omitted from the canonical:\n%s", canon)
	}
	raw, err := ComposeBytes(d)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(raw), "healthcheck") {
		t.Errorf("an empty healthcheck must not be generated:\n%s", raw)
	}
}

func TestHealthcheckAccessorDefaults(t *testing.T) {
	var none *Healthcheck
	for _, h := range []*Healthcheck{none, {}, {Test: []string{"curl"}}} {
		if h.IntervalD() != 30*time.Second || h.TimeoutD() != 30*time.Second || h.RetriesN() != 3 || h.StartPeriodD() != 0 {
			t.Errorf("%+v: defaults = %v %v %d %v, want 30s 30s 3 0s", h, h.IntervalD(), h.TimeoutD(), h.RetriesN(), h.StartPeriodD())
		}
	}
	// A value validation would reject never leaks out of an accessor.
	bad := &Healthcheck{Test: []string{"curl"}, Interval: "soon", Timeout: "-5s", Retries: -2, StartPeriod: "x"}
	if bad.IntervalD() != 30*time.Second || bad.TimeoutD() != 30*time.Second || bad.RetriesN() != 3 || bad.StartPeriodD() != 0 {
		t.Errorf("unusable values must fall back to the defaults")
	}
}

func TestServiceSelfHealingOnUnhealthy(t *testing.T) {
	doc := func(sh string) []byte {
		return []byte(docWith("  compose:\n    services:\n      web:\n        image: nginx:1\n        healthcheck: [curl, -f, http://localhost/health]\n" + sh))
	}
	d, err := Parse(doc(""))
	if err != nil {
		t.Fatal(err)
	}
	if got := d.Spec.Compose.Services["web"].OnUnhealthy(); got != OnUnhealthyRestart {
		t.Errorf("unset on_unhealthy = %q, want restart", got)
	}
	if canon, _ := Canonical(d); strings.Contains(string(canon), "self_healing") {
		t.Errorf("an unset per-service self_healing must be omitted from the canonical:\n%s", canon)
	}
	for _, v := range []string{"restart", "notify"} {
		d, err := Parse(doc("        self_healing:\n          on_unhealthy: " + v + "\n"))
		if err != nil {
			t.Fatalf("on_unhealthy %s rejected: %v", v, err)
		}
		canon, err := Canonical(d)
		if err != nil {
			t.Fatal(err)
		}
		d2, err := Parse(canon)
		if err != nil {
			t.Fatalf("canonical did not re-parse: %v\n%s", err, canon)
		}
		if got := d2.Spec.Compose.Services["web"].OnUnhealthy(); got != v {
			t.Errorf("on_unhealthy %s round-tripped as %q:\n%s", v, got, canon)
		}
	}
	for name, sh := range map[string]string{
		"unknown value": "        self_healing:\n          on_unhealthy: ignore\n",
		"unknown key":   "        self_healing:\n          on_crash: notify\n",
		"app-level key": "        self_healing:\n          attempt_cap: 3\n",
	} {
		if _, err := Parse(doc(sh)); err == nil {
			t.Errorf("%s: must be rejected", name)
		}
	}
	// The per-service block doesn't disturb the app-level ladder tunables.
	both := docWith("  compose:\n    services:\n      web:\n        image: nginx:1\n        self_healing: {on_unhealthy: notify}\n  self_healing:\n    attempt_cap: 5\n")
	d, err = Parse([]byte(both))
	if err != nil {
		t.Fatalf("per-service + app-level self_healing rejected: %v", err)
	}
	if d.Spec.SelfHealing == nil || d.Spec.SelfHealing.AttemptCap != 5 || d.Spec.Compose.Services["web"].OnUnhealthy() != OnUnhealthyNotify {
		t.Errorf("self_healing blocks parsed wrong: app=%+v svc=%q", d.Spec.SelfHealing, d.Spec.Compose.Services["web"].OnUnhealthy())
	}
}
