func TestHealthcheckArrayFormByteIdentical(t *testing.T) {
	d, err := Parse([]byte(legacyHealthDef))
	if err != nil {
		t.Fatalf("existing-style definition rejected: %v", err)
	}
	canon, err := Canonical(d)
	if err != nil {
		t.Fatal(err)
	}
	if string(canon) != legacyHealthCanonical {
		t.Fatalf("canonical changed for an array healthcheck:\n--- got\n%s\n--- want\n%s", canon, legacyHealthCanonical)
	}
	// A stored canonical re-parses and re-marshals to itself (the read path is a fixed point).
	stored, err := Parse([]byte(legacyHealthCanonical))
	if err != nil {
		t.Fatalf("stored canonical no longer parses: %v", err)
	}
	if again, _ := Canonical(stored); string(again) != legacyHealthCanonical {
		t.Fatalf("stored canonical did not re-marshal byte-identically:\n%s", again)
	}
	raw, err := ComposeBytes(stored)
	if err != nil {
		t.Fatal(err)
	}
	if string(raw) != legacyHealthCompose {
		t.Fatalf("generated compose changed for an array healthcheck:\n--- got\n%s\n--- want\n%s", raw, legacyHealthCompose)
	}
}

func healthDoc(healthcheck string) []byte {
	return []byte(docWith("  compose:\n    services:\n      web:\n        image: nginx:1\n        healthcheck: " + healthcheck + "\n"))
}

func TestHealthcheckMappingForm(t *testing.T) {
	src := docWith(`  compose:
    services:
      web:
        image: nginx:1
        healthcheck:
          test: [wget, -qO-, http://localhost:3000/health]
          interval: 10s
          timeout: 5s
          retries: 4
          start_period: 60s
`)
	d, err := Parse([]byte(src))
	if err != nil {
		t.Fatalf("mapping healthcheck rejected: %v", err)
	}
	hc := d.Spec.Compose.Services["web"].Healthcheck
	if hc == nil || strings.Join(hc.Test, " ") != "wget -qO- http://localhost:3000/health" {
		t.Fatalf("test not parsed: %+v", hc)
	}
	if hc.IntervalD() != 10*time.Second || hc.TimeoutD() != 5*time.Second || hc.RetriesN() != 4 || hc.StartPeriodD() != time.Minute {
		t.Errorf("accessors = %v %v %d %v", hc.IntervalD(), hc.TimeoutD(), hc.RetriesN(), hc.StartPeriodD())
	}

	// The canonical keeps the mapping and re-parses to the same values.
	canon, err := Canonical(d)
	if err != nil {
		t.Fatal(err)
	}
	wantCanon := "        healthcheck:\n          test:\n            - wget\n            - -qO-\n            - http://localhost:3000/health\n" +
		"          interval: 10s\n          timeout: 5s\n          retries: 4\n          start_period: 60s\n"
	if !strings.Contains(string(canon), wantCanon) {
		t.Errorf("canonical missing the mapping healthcheck:\n%s", canon)
	}
	d2, err := Parse(canon)
	if err != nil {
		t.Fatalf("canonical did not re-parse: %v\n%s", err, canon)
	}
	if got := d2.Spec.Compose.Services["web"].Healthcheck; got == nil || !reflect.DeepEqual(*got, *hc) {
		t.Errorf("healthcheck did not round-trip: %+v", got)
	}

	// The generated compose carries every timing key and passes §5.6 + the full reconcile gate.
	raw, err := ComposeBytes(d)
	if err != nil {
		t.Fatal(err)
	}
	wantCompose := "        healthcheck:\n            test:\n                - CMD\n                - wget\n                - -qO-\n                - http://localhost:3000/health\n" +
		"            interval: 10s\n            timeout: 5s\n            retries: 4\n            start_period: 60s\n"
	if !strings.Contains(string(raw), wantCompose) {
		t.Errorf("generated compose missing the timing keys:\n%s", raw)
	}
	if strings.Contains(string(raw), "start_interval") {
		t.Errorf("start_interval must never be generated:\n%s", raw)
	}
	if res := compose.ValidateBytes(raw, compose.Env{}, "/run/app", compose.Options{}); !res.OK() {
		t.Fatalf("generated compose failed §5.6: %s", res.Error())
	}
	if err := Validate(d, "/run/app", compose.Env{}, nil); err != nil {
		t.Errorf("mapping healthcheck must pass the reconcile gate: %v", err)
	}
}

// A mapping with only `test` is the same healthcheck as the bare array, so it canonicalizes to
// the array form.
func TestHealthcheckMappingTestOnlyCanonicalizesToArray(t *testing.T) {
	fromMap, err := Parse(healthDoc("{test: [wget, -qO-, http://localhost/health]}"))
	if err != nil {
		t.Fatal(err)
	}
	fromArr, err := Parse(healthDoc("[wget, -qO-, http://localhost/health]"))
	if err != nil {
		t.Fatal(err)
	}
	a, _ := Canonical(fromMap)
	b, _ := Canonical(fromArr)
	if string(a) != string(b) {
		t.Errorf("test-only mapping should canonicalize to the array form:\n--- mapping\n%s\n--- array\n%s", a, b)
	}
	if !strings.Contains(string(a), "healthcheck:\n          - wget\n") {
		t.Errorf("expected the bare array form:\n%s", a)
	}
}

func TestHealthcheckAccepts(t *testing.T) {
	for name, hc := range map[string]string{
		"array":                    "[curl, -f, http://localhost/health]",
		"array keeps CMD (compat)": "[CMD, curl, -f, http://localhost/health]",
		"test only":                "{test: [curl, -f, http://localhost/health]}",
		"interval floor":           "{test: [curl], interval: 1s}",
		"interval ceiling":         "{test: [curl], interval: 10m}",
		"timeout floor":            "{test: [curl], timeout: 1s}",
		"timeout ceiling":          "{test: [curl], timeout: 5m}",
		"retries floor":            "{test: [curl], retries: 1}",
		"retries ceiling":          "{test: [curl], retries: 20}",
		"start_period zero":        "{test: [curl], start_period: 0s}",
		"start_period bare zero":   "{test: [curl], start_period: 0}",
		"start_period ceiling":     "{test: [curl], start_period: 30m}",
		"compound duration":        "{test: [curl], interval: 1m30s}",
		"null field is unset":      "{test: [curl], interval: ~, retries: ~}",
	} {
		if _, err := Parse(healthDoc(hc)); err != nil {
			t.Errorf("%s: %s rejected: %v", name, hc, err)
		}
	}
}

