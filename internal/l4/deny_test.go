func denyList(ss ...string) []netip.Prefix {
	out := make([]netip.Prefix, len(ss))
	for i, s := range ss {
		out[i] = netip.MustParsePrefix(s)
	}
	return out
}

// deny lines are IPv4 only (the listeners are IPv4), canonical, sorted and unique, in the stream block
// before any server; ranges wider than /24 and non-public ranges are left out.
func TestRenderDenyLines(t *testing.T) {
	routes := []Route{
		{Listen: 53, Protocol: "udp", Service: "coredns", Port: 5353, Pool: []string{"10.0.0.7:5353"}},
		{Listen: 853, Protocol: "tcp", Service: "coredns", Port: 8853, Pool: []string{"10.0.0.5:8853"}},
	}
	deny := append(denyList("203.0.113.7/32", "198.51.100.0/24", "2001:db8:1:2::/64", "203.0.113.7/32",
		"10.0.0.0/24", "127.0.0.1/32", "100.64.0.1/32", "1.2.0.0/16", "::ffff:192.0.2.1/128"),
		netip.PrefixFrom(netip.MustParseAddr("192.0.2.9"), 24), netip.Prefix{})
	out, err := RenderDeny(routes, deny)
	if err != nil {
		t.Fatal(err)
	}
	var lines []string
	for _, l := range strings.Split(out, "\n") {
		if strings.HasPrefix(strings.TrimSpace(l), "deny ") {
			lines = append(lines, strings.TrimSpace(l))
		}
	}
	want := []string{"deny 192.0.2.0/24;", "deny 198.51.100.0/24;", "deny 203.0.113.7/32;"}
	if strings.Join(lines, "|") != strings.Join(want, "|") {
		t.Errorf("deny lines = %q, want %q\n%s", lines, want, out)
	}
	stream := strings.Index(out, "stream {\n")
	firstDeny := strings.Index(out, "    deny ")
	firstServer := strings.Index(out, "    upstream ")
	if stream < 0 || firstDeny < stream || firstServer < firstDeny {
		t.Errorf("deny lines must open the stream block, before any upstream/server:\n%s", out)
	}
	// Without a block list the render is exactly Render's.
	plain, err := Render(routes)
	if err != nil {
		t.Fatal(err)
	}
	if none, _ := RenderDeny(routes, nil); none != plain {
		t.Error("RenderDeny(routes, nil) must equal Render(routes)")
	}
	if none, _ := RenderDeny(routes, denyList("2001:db8::/64", "10.1.1.1/32")); none != plain {
		t.Error("a block list with nothing to deny on IPv4 listeners must render like none")
	}
	if strings.Contains(plain, "deny") {
		t.Errorf("Render must carry no deny line:\n%s", plain)
	}
}

// Render keeps its exact output (no block list): pinned against a fixed render.
func TestRenderUnchangedWithoutDeny(t *testing.T) {
	out, err := Render([]Route{{Listen: 53, Protocol: "udp", Service: "coredns", Port: 5353, LB: "hash_client_ip", Pool: []string{"10.0.0.7:5353"}}})
	if err != nil {
		t.Fatal(err)
	}
	const want = "# generated by Mooring — do not edit\n" +
		"include /etc/nginx/modules-enabled/*.conf;\n" +
		"worker_processes auto;\n" +
		"pid nginx.pid;\n" +
		"error_log stderr;\n" +
		"events {}\n" +
		"stream {\n" +
		"    upstream l4_53_udp {\n" +
		"        hash $remote_addr consistent;\n" +
		"        server 10.0.0.7:5353;\n" +
		"    }\n" +
		"    server {\n" +
		"        listen 53 udp;\n" +
		"        proxy_timeout 5s;\n" +
		"        proxy_pass l4_53_udp;\n" +
		"    }\n" +
		"}\n"
	if out != want {
		t.Errorf("Render changed:\n%s", out)
	}
}

// A kernel route is still not rendered with a block list (Docker forwards it; deny can't reach it).
func TestRenderDenyKernelRoutesUnaffected(t *testing.T) {
	out, err := RenderDeny([]Route{
		{AppID: "dns", Listen: 53, Protocol: "udp", Service: "coredns", Port: 5353, Forward: "kernel", Pool: []string{"172.18.0.5:5353"}},
	}, denyList("203.0.113.7/32"))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(out, "listen 53") || strings.Contains(out, "172.18.0.5") {
		t.Errorf("a kernel route must render nothing:\n%s", out)
	}
	if !strings.Contains(out, "deny 203.0.113.7/32;") {
		t.Errorf("the deny line is still rendered for the proxy listeners:\n%s", out)
	}
}

// Reconcile renders SetDeny's list; when nginx -t refuses the config only with its deny lines, the
// config without them is applied and DenyErr says why, cleared once a config with the list passes.
func TestReconcileRetriesWithoutDenyLines(t *testing.T) {
	s := newSup(t)
	refuseDeny := true
	var tested []string
	s.testConf = func(_ context.Context, p string) error {
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		tested = append(tested, string(b))
		if refuseDeny && strings.Contains(string(b), "deny ") {
			return errors.New(`unknown directive "deny"`)
		}
		return nil
	}
	reloads := 0
	s.sighup = func(*os.Process) error { reloads++; return nil }
	s.proc = &os.Process{Pid: 1}
	routes := []Route{{Listen: 853, Protocol: "tcp", Service: "coredns", Port: 8853, Pool: []string{"10.0.0.5:8853"}}}
	s.SetDeny(func() []netip.Prefix { return denyList("203.0.113.7/32") })

	if err := s.Reconcile(context.Background(), routes); err != nil {
		t.Fatalf("a refused block list must not fail the reconcile: %v", err)
	}
	if len(tested) != 2 || !strings.Contains(tested[0], "deny 203.0.113.7/32;") || strings.Contains(tested[1], "deny") {
		t.Fatalf("want a test with the deny lines then one without, got %d tests", len(tested))
	}
	live, _ := os.ReadFile(s.ConfigPath)
	if strings.Contains(string(live), "deny") || !strings.Contains(string(live), "listen 853;") {
		t.Errorf("live config must be the render without deny lines:\n%s", live)
	}
	if e := s.DenyErr(); !strings.Contains(e, `unknown directive "deny"`) {
		t.Errorf("DenyErr = %q", e)
	}
	if reloads != 1 {
		t.Errorf("reloads = %d, want 1", reloads)
	}

	refuseDeny = false
	tested = nil
	if err := s.Reconcile(context.Background(), routes); err != nil {
		t.Fatal(err)
	}
	live, _ = os.ReadFile(s.ConfigPath)
	if len(tested) != 1 || !strings.Contains(string(live), "deny 203.0.113.7/32;") || s.DenyErr() != "" {
		t.Errorf("an accepted block list must be applied and clear DenyErr (%d tests, err %q):\n%s", len(tested), s.DenyErr(), live)
	}
}

// When the config fails without its deny lines too, nothing changes and the error is returned.
func TestReconcileDenyRetryKeepsLastGood(t *testing.T) {
	s := newSup(t)
	if err := os.WriteFile(s.ConfigPath, []byte("GOOD"), 0o644); err != nil {
		t.Fatal(err)
	}
	n := 0
	s.testConf = func(context.Context, string) error { n++; return errors.New("bad") }
	s.SetDeny(func() []netip.Prefix { return denyList("203.0.113.7/32") })
	err := s.Reconcile(context.Background(), []Route{{Listen: 853, Protocol: "tcp", Service: "c", Port: 8853, Pool: []string{"10.0.0.5:8853"}}})
	if err == nil || !strings.Contains(err.Error(), "last-good") {
		t.Fatalf("err = %v", err)
	}
	if got, _ := os.ReadFile(s.ConfigPath); string(got) != "GOOD" || n != 2 || s.DenyErr() != "" {
		t.Errorf("live %q, %d tests, DenyErr %q", got, n, s.DenyErr())
	}
	// No deny lines: a refusal is not retried.
	n = 0
	s.SetDeny(func() []netip.Prefix { return nil })
	if err := s.Reconcile(context.Background(), nil); err == nil || n != 1 {
		t.Errorf("without deny lines: err %v after %d tests, want one test", err, n)
	}
}

// A block list nginx keeps refusing is logged when the reason changes, not on every reconcile (the
// loop runs every 15 s), and once more when nginx takes the list again.
func TestReconcileLogsARefusedDenyListOnce(t *testing.T) {
	s := newSup(t)
	var logged bytes.Buffer
	s.Log = slog.New(slog.NewTextHandler(&logged, nil))
	why := `unknown directive "deny"`
	s.testConf = func(_ context.Context, p string) error {
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		if why != "" && strings.Contains(string(b), "deny ") {
			return errors.New(why)
		}
		return nil
	}
	s.sighup = func(*os.Process) error { return nil }
	s.proc = &os.Process{Pid: 1}
	routes := []Route{{Listen: 853, Protocol: "tcp", Service: "coredns", Port: 8853, Pool: []string{"10.0.0.5:8853"}}}
	s.SetDeny(func() []netip.Prefix { return denyList("203.0.113.7/32") })
	reconcile := func(n int) {
		t.Helper()
		for i := 0; i < n; i++ {
			if err := s.Reconcile(context.Background(), routes); err != nil {
				t.Fatal(err)
			}
		}
	}
	refusals := func() int { return strings.Count(logged.String(), "nginx refused the block list") }
	reconcile(4)
	if n := refusals(); n != 1 {
		t.Errorf("4 reconciles with the same refusal logged it %d times, want 1", n)
	}
	why = `"deny" directive is not allowed here`
	reconcile(3)
	if n := refusals(); n != 2 || !strings.Contains(s.DenyErr(), why) {
		t.Errorf("a different refusal: logged %d times, want 2 (DenyErr %q)", n, s.DenyErr())
	}
	why = ""
	reconcile(3)
	if n := strings.Count(logged.String(), "nginx takes the block list again"); n != 1 || refusals() != 2 || s.DenyErr() != "" {
		t.Errorf("accepted again: logged %d times, want 1 (refusals %d, DenyErr %q)", n, refusals(), s.DenyErr())
	}
	why = `unknown directive "deny"`
	reconcile(2)
	if n := refusals(); n != 3 {
		t.Errorf("refused again after it worked: logged %d times, want 3", n)
	}
}
